    fila = page.locator('#listaPacientes .fila-pac', has_text='Otero')
    check('Próxima cita:' in fila.inner_text(), 'la lista de pacientes muestra su próxima cita')
    fila.locator('a').click(); page.wait_for_timeout(150)
    check('Próxima cita:' in page.locator('.sticky-head').inner_text(), 'la cabecera de la ficha también')
    page.get_by_role('tab', name='Citas').click(); page.wait_for_timeout(150)
    check(page.evaluate('location.hash') == '#/paciente/p2/citas', 'pestaña Citas con su dirección')
