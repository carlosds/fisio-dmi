import json, sys, urllib.request
from playwright.sync_api import sync_playwright
PORT = sys.argv[1]; BASE = f'http://127.0.0.1:{PORT}'
fails = []
def check(c, m):
    print(('  ok  ' if c else '  FALLA ') + m)
    if not c: fails.append(m)
st = lambda: json.loads(urllib.request.urlopen(BASE + '/__state').read())

with sync_playwright() as pw:
    b = pw.chromium.launch(); page = b.new_page(viewport={'width': 1300, 'height': 900})
    errs = []; page.on('pageerror', lambda e: errs.append(str(e)))
    respuestas = []   # respuestas para las próximas ventanas (None = aceptar lo propuesto, False = cancelar)
    dialogos = []
    def on_dialog(d):
        dialogos.append(d.message)
        r = respuestas.pop(0) if respuestas else None
        if r is False: d.dismiss()
        elif r is None: d.accept()
        else: d.accept(r)
    page.on('dialog', on_dialog)
    page.goto(BASE + '/'); page.wait_for_selector('#listaPacientes'); page.evaluate('descartarNovedades()')
    page.evaluate("db.patients.push({ id: 'p2', nombre: 'Luis', apellidos: 'Otero', telefono: '', email: '', fechaAlta: '2026-01-01', foto: '' }); render()")
    L = page.evaluate("addDays(iso(inicioSemana(new Date())), 7)")   # lunes de la semana que viene
    d = lambda n: page.evaluate(f"addDays('{L}', {n})")
    m = page.locator('#modal')
    citas = lambda: page.evaluate("db.citas.map(c => ({ ...c })).sort((a, b) => (a.fecha + a.hora).localeCompare(b.fecha + b.hora))")

    print('\n[1] Pantalla Agenda')
    page.get_by_role('button', name='Agenda', exact=True).click(); page.wait_for_selector('#sec-agenda')
    check(page.evaluate('location.hash') == '#/agenda', 'tiene su dirección (#/agenda)')
    check(page.locator('.ag-col').count() == 5 and 'Semana del' in page.locator('#sec-agenda h3').inner_text(), 'la semana muestra de lunes a viernes')
    check(page.locator('.ag-dia.hoy').count() in (0, 1), 'el día de hoy se resalta (si cae entre semana)')
    page.get_by_role('button', name='Siguiente').click(); page.wait_for_timeout(100)
    check(page.evaluate("iso(inicioSemana(ui.agFecha))") == L, '«Siguiente» pasa a la semana que viene')

    print('\n[2] Nueva cita')
