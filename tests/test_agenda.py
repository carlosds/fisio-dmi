    m.get_by_role('button', name='Dar cita').click(); page.wait_for_timeout(300)
    s = st()
    check(len(s['citas']) == 1 and {k: s['citas'][0][k] for k in ('patientId', 'fecha', 'hora', 'duracion', 'serieId')} == {'patientId': 'p1', 'fecha': L, 'hora': '10:00', 'duracion': 45, 'serieId': ''}, 'se guarda la cita (también en el servidor)')
