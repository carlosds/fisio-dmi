    page.reload(); page.wait_for_selector('#sec-agenda'); page.wait_for_timeout(500)
    check(sum(1 for c in st()['citas'] if c['serieId'] == sid) == n, 'al abrir la aplicación la serie vuelve a tener sus citas de los próximos 6 meses')

