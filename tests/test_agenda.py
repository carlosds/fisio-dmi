    page.select_option('#agDur', '60')
    check(st()['ajustes'].get('agendaInicio') == '07:00' and st()['ajustes'].get('agendaDias') == '123456' and st()['ajustes'].get('citaDuracion') == '60', 'horario, días y duración se guardan')
    page.evaluate("go('agenda')"); page.wait_for_timeout(150)
    check(page.locator('.ag-col').count() == 6 and page.locator('.ag-h').first.inner_text() == '07:00', 'la agenda muestra el sábado y empieza a las 07:00')
