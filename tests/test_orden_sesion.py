# Orden de los ejercicios: ya no se ordena en Pautas; sí en cada sesión (ventana del día, vista de día y al añadir)
# y al añadir al plan en casa (días y «A elegir») y a las plantillas.
# Uso: python3 mock_server.py PUERTO seed_nuevo.json & ; python3 test_orden_sesion.py PUERTO
import json, sys, urllib.request
from playwright.sync_api import sync_playwright
PORT = sys.argv[1]; BASE = f'http://127.0.0.1:{PORT}'
fails = []
def check(c, m):
    print(('  ok  ' if c else '  FALLA ') + m)
    if not c: fails.append(m)
st = lambda: json.loads(urllib.request.urlopen(BASE + '/__state').read())

with sync_playwright() as pw:
    b = pw.chromium.launch(); page = b.new_page(viewport={'width': 1300, 'height': 900})
    errs = []; page.on('pageerror', lambda e: errs.append(str(e))); page.on('dialog', lambda d: d.accept())
    page.goto(BASE + '/'); page.wait_for_selector('#listaPacientes')
    ev = page.evaluate
    hoy = ev('todayIso()'); man = ev("addDays(todayIso(), 1)")
    ev(f"""db.citas.push({{ id: 'c1', patientId: 'p1', fecha: '{hoy}', hora: '23:00', duracion: 30, nota: '', color: '', serieId: '', fechaSerie: '' }});
        openPatient('p1')""")
    page.wait_for_selector('#sec-pautas')

    print('\n[1] Pautas: sin orden')
    sec = page.locator('#sec-pautas')
    check(sec.get_by_role('button', name='Subir').count() == 0 and sec.get_by_role('button', name='Bajar').count() == 0, 'las pautas ya no tienen flechas')
    check('usa las flechas' not in sec.inner_text(), 'ni el texto de las flechas')

    print('\n[2] Ordenar en la ventana del día (Puntuar)')
    nombres = lambda sel='#modal #secPun': page.locator(f'{sel} .ej-nom-dia').all_inner_texts()
    ev(f"puntuarCita('p1', '{hoy}', 'c1')"); page.wait_for_selector('#modal #secPun .ej-dia')
    check(nombres() == ['Puente glúteo', 'Plancha lateral', 'Estiramiento isquios'], f'por defecto, el orden de las pautas {nombres()}')
    page.locator('#modal #secPun .ej-dia', has_text='Estiramiento isquios').get_by_role('button', name='Subir Estiramiento isquios').click(); page.wait_for_timeout(150)
    check(nombres() == ['Estiramiento isquios', 'Puente glúteo', 'Plancha lateral'], f'subir un ejercicio suelto lo pone delante del bloque {nombres()}')
    check(page.locator('#modal #secPun .grp-titulo', has_text='Core básico').get_by_role('button', name='Bajar Core básico').is_disabled(), 'el bloque ya es el último: su ↓ está desactivado')
    page.locator('#modal').get_by_text('Cerrar', exact=True).click(); page.wait_for_timeout(300)
    s = st()
    check(s.get('ordenSesiones', {}).get(f'p1|{hoy}|c1') == ['e3', 'e1', 'e2'], f"se guarda el orden de esa sesión ({s.get('ordenSesiones')})")
    check(ev(f"exercisesSesion('p1', '{man}', '').map(i => i.exercise.nombre)") == ['Puente glúteo', 'Plancha lateral', 'Estiramiento isquios'], 'los demás días no cambian')

    print('\n[3] Vista de día del calendario')
    ev(f"irTab('calendario'); ui.vista = 'dia'; ui.fecha = fromIso('{hoy}'); render()"); page.wait_for_timeout(200)
    check(nombres('#calCuerpo') == ['Estiramiento isquios', 'Puente glúteo', 'Plancha lateral'], 'la vista de día sigue el orden de la sesión')
    page.locator('#calCuerpo .grp-titulo', has_text='Core básico').get_by_role('button', name='Subir Core básico').click(); page.wait_for_timeout(150)
    check(nombres('#calCuerpo') == ['Puente glúteo', 'Plancha lateral', 'Estiramiento isquios'], 'y también se ordena desde ahí')
    ev("ui.vista = 'semana'; render()"); page.wait_for_timeout(150)
    check(page.locator('#calCuerpo .day.today .nom').all_inner_texts() == ['Puente glúteo', 'Plancha lateral', 'Estiramiento isquios'], 'la semana muestra el día en ese orden')

    print('\n[4] Al añadir a la sesión, se coloca')
    ev(f"puntuarCita('p1', '{hoy}', 'c1'); tabDia('anadir')"); page.wait_for_selector('#ordenAdd')
    orden = lambda: [t.replace('Nuevo', '').strip() for t in page.locator('#ordenAdd .ord > span:first-child').all_inner_texts()]
    check(orden() == ['Core básico', 'Estiramiento isquios'], f'el panel «Orden» muestra lo que ya hay {orden()}')
    page.locator('#modal .exItem', has_text='Respiración diafragmática').locator('input').check(); page.wait_for_timeout(100)
    check(orden() == ['Core básico', 'Estiramiento isquios', 'Respiración diafragmática'] and page.locator('#ordenAdd .ord.nuevo').count() == 1, 'lo marcado sale al final, como «Nuevo»')
    for _ in range(2): page.locator('#ordenAdd .ord.nuevo').get_by_role('button', name='Subir Respiración diafragmática').click()
    check(orden()[0] == 'Respiración diafragmática', 'y se puede subir antes de añadirlo')
    page.locator('#modal .exItem', has_text='Respiración diafragmática').locator('input').uncheck(); page.wait_for_timeout(100)
    check(page.locator('#ordenAdd .ord.nuevo').count() == 0, 'al desmarcarlo, sale del panel')
    page.locator('#modal .exItem', has_text='Respiración diafragmática').locator('input').check(); page.wait_for_timeout(100)
    page.locator('#ordenAdd .ord.nuevo').get_by_role('button', name='Subir Respiración diafragmática').click()
    page.get_by_role('button', name='Añadir a la sesión').click(); page.wait_for_timeout(300)
    check(nombres() == ['Puente glúteo', 'Plancha lateral', 'Respiración diafragmática', 'Estiramiento isquios'], f'se añade en el sitio elegido {nombres()}')
    ev('closeModal()')

    print('\n[5] Plan en casa: al añadir a un día y a «A elegir»')
    ev("""(() => { const pl = { id: 'pl1', patientId: 'p1', nombre: 'Plan', inicio: todayIso(), fin: addDays(todayIso(), 13), duracion: 2, unidad: 'semanas', notas: '', creado: todayIso(), items: [] }; db.planes.push(pl); irTab('casa'); abrirPlanCasa('pl1'); })()""")
    page.wait_for_selector('.pc-elegir')
    ev("openAddPl(0)"); page.wait_for_selector('#ordenAdd')
    for n in ['Puente glúteo', 'Plancha lateral']: page.locator('#modal .exItem', has_text=n).locator('input').check()
    page.locator('#ordenAdd .ord', has_text='Plancha lateral').get_by_role('button', name='Subir Plancha lateral').click()
    page.get_by_role('button', name='Añadir', exact=True).click(); page.wait_for_timeout(200)
    elegir = lambda: ev("gruposPlantilla(docActual(), 0).flatMap(g => g.items.map(i => getE(i.exerciseId).nombre))")
    check(elegir() == ['Plancha lateral', 'Puente glúteo'], f'«A elegir» respeta el orden del panel {elegir()}')
    ev("openAddPl(0)"); page.wait_for_selector('#ordenAdd')
    check(orden() == ['Plancha lateral', 'Puente glúteo'], 'al volver a añadir, el panel muestra lo que ya hay')
    page.locator('#modal .bItem', has_text='Core básico').locator('input.bCheck').check() if page.locator('#modal .bItem', has_text='Core básico').count() else None
    page.locator('#modal .exItem', has_text='Estiramiento isquios').locator('input').check()
    page.locator('#ordenAdd .ord.nuevo', has_text='Estiramiento isquios').get_by_role('button', name='Subir Estiramiento isquios').click()
    page.locator('#ordenAdd .ord.nuevo', has_text='Estiramiento isquios').get_by_role('button', name='Subir Estiramiento isquios').click()
    page.get_by_role('button', name='Añadir', exact=True).click(); page.wait_for_timeout(200)
    check(elegir()[0] == 'Estiramiento isquios', f'lo nuevo se puede poner el primero {elegir()}')
    dia = ev("(() => { const t = docActual(); for (let d = 1; d <= 14; d++) if (diaEnPlan(t, d)) return d; })()")
    ev(f"openAddPl({dia})"); page.wait_for_selector('#ordenAdd')
    check(page.locator('#ordenAdd .ord').count() == 0, 'un día vacío empieza sin nada en el panel')
    page.locator('#modal .exItem', has_text='Respiración diafragmática').locator('input').check()
    page.locator('#modal .bItem', has_text='Core básico').locator('input.bCheck').check(); page.wait_for_timeout(100)
    check(orden()[-1] == 'Core básico', 'los bloques también salen en el panel')
    page.locator('#ordenAdd .ord.nuevo', has_text='Core básico').get_by_role('button', name='Subir Core básico').click()
    page.get_by_role('button', name='Añadir', exact=True).click(); page.wait_for_timeout(200)
    check(ev(f"gruposPlantilla(docActual(), {dia}).map(g => g.clave ? 'Core' : getE(g.items[0].exerciseId).nombre)") == ['Core', 'Respiración diafragmática'], 'el bloque queda delante, como se eligió')
    ev(f"openDiaPl({dia})"); page.wait_for_selector('.dc-lista')
    page.get_by_role('button', name='+ Añadir a este día…').click(); page.wait_for_selector('#ordenAdd')
    check(page.locator('#ordenAdd .ord').count() == 2, '«Editar» → «+ Añadir…» abre la misma ventana, con el orden')
    page.get_by_role('button', name='Cancelar').click(); page.wait_for_selector('.dc-lista')
    check(page.locator('.dc-lista').count() == 1, 'y «Cancelar» vuelve a «Editar»')
    ev('closeModal()')

    print('\n[6] Plantillas')
    ev("db.plantillas.push({ id: 't1', nombre: 'Semana tipo', semanas: 1, duracion: 1, unidad: 'semanas', ciclo: 1, notas: '', creada: todayIso(), items: [], aplicaciones: [] }); verPlantilla('t1')")
    page.wait_for_selector('#sec-plantilla')
    ev("openAddPl(1)"); page.wait_for_selector('#ordenAdd')
    for n in ['Puente glúteo', 'Estiramiento isquios']: page.locator('#modal .exItem', has_text=n).locator('input').check()
    page.locator('#ordenAdd .ord', has_text='Estiramiento isquios').get_by_role('button', name='Subir Estiramiento isquios').click()
    page.get_by_role('button', name='Añadir', exact=True).click(); page.wait_for_timeout(200)
    check(ev("gruposPlantilla(docActual(), 1).map(g => getE(g.items[0].exerciseId).nombre)") == ['Estiramiento isquios', 'Puente glúteo'], 'en las plantillas también')

    check(not errs, f'sin errores JS {errs}')
    b.close()
print('\nRESULTADO:', 'TODO OK' if not fails else f'{len(fails)} FALLOS')
sys.exit(1 if fails else 0)
