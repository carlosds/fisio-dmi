# Filtro «solo ejercicios», tooltip de bloques, buscador de bloques, pautas (orden, continua), pestañas, hitos y puntuaciones agrupadas.
# Uso: python3 mock_server.py PUERTO seed_nuevo.json & ; python3 test_lote.py PUERTO
import sys, re
from playwright.sync_api import sync_playwright
ok = True
def check(c, m):
    global ok; ok = ok and bool(c); print(('  OK    ' if c else '  FALLO ') + m)
with sync_playwright() as pw:
    br = pw.chromium.launch(executable_path='/opt/pw-browsers/chromium', headless=True)
    page = br.new_page(viewport={'width': 1300, 'height': 900})
    errors = []; page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('dialog', lambda d: d.accept())
    page.goto(f'http://127.0.0.1:{sys.argv[1]}/'); page.wait_for_selector('#main')

    print('\n[1] Tooltip de bloques en Ejercicios y buscador de bloques')
    page.get_by_role('button', name='Biblioteca', exact=True).click(); page.get_by_role('button', name='Ejercicios', exact=True).click(); page.wait_for_timeout(200)
    check('En 1 bloque' in page.locator('#listaEjercicios .item', has_text='Puente glúteo').inner_text(), 'badge «En 1 bloque» visible en la lista')
    check('En ' not in page.locator('#listaEjercicios .item', has_text='Estiramiento isquios').inner_text(), 'sin badge si no está en ningún bloque')
    page.evaluate("go('bloques')"); page.wait_for_timeout(150)
    page.fill('#buscarBl', 'plancha'); page.wait_for_timeout(150)
    check(page.locator('#listaBloques .item').count() == 1, 'el buscador de bloques encuentra por nombre de ejercicio')
    page.fill('#buscarBl', 'core'); page.wait_for_timeout(150)
    check(page.locator('#listaBloques .item').count() == 1, '…y por nombre de bloque')
    page.fill('#buscarBl', 'zzz'); page.wait_for_timeout(150)
    check(page.locator('#listaBloques .item').count() == 0, '…y sin coincidencias no muestra nada')

    print('\n[2] Filtro «Solo ejercicios» al asignar')
    page.get_by_role('button', name='Pacientes', exact=True).click(); page.locator('#listaPacientes .item a').first.click(); page.wait_for_selector('#sec-pautas')
    page.get_by_role('button', name='Asignar ejercicios').click()
    page.select_option('#aNivel', '__ej'); page.wait_for_timeout(100)
    vis = lambda sel: page.evaluate(f"[...document.querySelectorAll('#modal {sel}')].filter(e => e.style.display !== 'none').length")
    check(vis('.bItem') == 0 and vis('.exItem') == 4, 'solo se ven los ejercicios')
    check(page.evaluate("[...document.querySelectorAll('#modal .gTitulo')].filter(t => t.style.display !== 'none').map(t => t.textContent)") == ['Ejercicios'], 'solo queda el título «Ejercicios»')
    page.select_option('#aNivel', ''); page.wait_for_timeout(100)
    check(vis('.bItem') == 1 and vis('.exItem') == 4, '«Todos» vuelve a mostrar todo')
    page.locator('#modal button', has_text='Cancelar').click()

    print('\n[3] Orden de la sesión de hoy y calendarios')
    nombres = lambda: [t.strip() for t in page.locator('#sec-pautas .item > div:first-child > span:first-child').all_inner_texts()]
    check([re.sub(r'^\d+\.\s*', '', n) for n in nombres()] == ['Core básico', 'Estiramiento isquios'], f'orden inicial {nombres()}')
    check(page.locator('#sec-pautas').get_by_role('button', name='Subir').count() == 0, 'las pautas no se ordenan en su pestaña (se ordena cada sesión)')
    page.evaluate("ui.patientId = 'p1'; moverUnidadSesion(todayIso(), '', 'e3', -1)"); page.wait_for_timeout(200)   # como el ↑ de la sesión de hoy
    orden = page.evaluate("exercisesOn('p1', todayIso()).map(i => i.exercise.nombre)")
    check(orden == ['Estiramiento isquios', 'Puente glúteo', 'Plancha lateral'], f'exercisesOn respeta el orden: {orden}')
    page.get_by_role('tab', name='Calendario').click(); page.locator('#subCal').get_by_role('button', name='Calendario').click(); page.wait_for_timeout(100)
    page.get_by_role('button', name='Día', exact=True).first.click(); page.wait_for_timeout(200)
    check(page.locator('#sec-calendario .tabs:not(#subCal) button').all_inner_texts() == ['Día', 'Semana', 'Mes'], 'pestañas del calendario: Día, Semana, Mes')
    chips = page.locator('#sec-calendario .ej-dia .ej-nom-dia').all_inner_texts()
    check(chips == ['Estiramiento isquios', 'Puente glúteo', 'Plancha lateral'], f'vista Día en orden: {chips}')
    page.get_by_role('button', name='Semana', exact=True).first.click(); page.wait_for_timeout(200)
    hoy_chips = page.locator('#sec-calendario .day.today .nom').all_inner_texts()
    check(hoy_chips == ['Estiramiento isquios', 'Puente glúteo', 'Plancha lateral'], f'vista Semana en orden: {hoy_chips}')
    page.get_by_role('button', name='Mes', exact=True).first.click(); page.wait_for_timeout(200)
    info = page.locator('#sec-calendario .day.mes.today .mes-info').inner_text()
    check(info.strip() == '0 de 3 puntuados' and page.locator('#sec-calendario .day.mes.today .nom').count() == 0, f'vista Mes: la celda resume el día ({info!r})')
    page.get_by_role('tab', name='Calendario').click(); page.locator('#subCal').get_by_role('button', name='Resumen').click(); page.wait_for_timeout(100)
    check(page.locator('#sec-resumen .tabs:not(#subCal)').first.locator('button').all_inner_texts()[:3] == ['Día', 'Semana', 'Mes'], 'pestañas del resumen: Día, Semana, Mes')
    page.get_by_role('tab', name='Calendario').click(); page.locator('#subCal').get_by_role('button', name='Calendario').click(); page.wait_for_timeout(100)

    print('\n[4] Puntuaciones agrupadas por bloque, en una columna')
    page.locator('#sec-calendario .day.today').click(); page.wait_for_selector('#modal .grp-dia')
    ts = page.locator('#modal .grp-titulo').all_inner_texts()
    check([t.strip() for t in ts][:2] == ['Ejercicios sueltos', 'Core básico'] or [t.split('\n')[0].strip() for t in ts][:2] == ['Ejercicios sueltos', 'Core básico'] or ('Core básico' in ts[1] and 'sueltos' in ts[0]), f'títulos de grupo: {ts}')
    cajas = page.locator('#modal .ej-dia').evaluate_all("els => els.map(e => { const r = e.getBoundingClientRect(); return [Math.round(r.x), Math.round(r.y)] })")
    check(len(cajas) == 3 and len({c[0] for c in cajas}) == 1 and cajas == sorted(cajas, key=lambda c: c[1]), f'una sola columna, cada ejercicio debajo del anterior: {cajas}')
    bloque_y = page.locator('#modal .grp-titulo', has_text='Core básico').bounding_box()['y']
    ej_y = [page.locator('#modal .ej-dia .ej-nom-dia', has_text=n).bounding_box()['y'] for n in ('Puente glúteo', 'Plancha lateral')]
    check(all(y > bloque_y for y in ej_y), 'los ejercicios del bloque van debajo de su nombre')
    page.keyboard.press('Escape')

    print('\n[5] «Editar» pauta: fecha fin y continua')
    page.get_by_role('tab', name='Pautas').click(); page.wait_for_timeout(100)
    fin = page.evaluate("todayIso()")
    def editar(texto):
        page.locator('#sec-pautas .item', has_text=texto).get_by_role('button', name='Editar', exact=True).click(); page.wait_for_selector('#epIni')
    editar('Estiramiento isquios')
    page.select_option('#epTipo', 'fecha'); page.fill('#epFin', fin)
    page.locator('#modal').get_by_role('button', name='Guardar', exact=True).click(); page.wait_for_timeout(200)
    check(page.evaluate("db.pautas.find(p => p.exerciseId === 'e3').hasta") == fin, 'se finaliza')
    editar('Estiramiento isquios')
    check(page.locator('#epTipo').input_value() == 'fecha' and page.locator('#epFin').input_value() == fin, 'el modal muestra la fecha de fin actual')
    page.select_option('#epTipo', 'continua'); check(page.locator('#epFinWrap').is_hidden(), '«Continua» oculta la fecha de fin')
    page.locator('#modal').get_by_role('button', name='Guardar', exact=True).click(); page.wait_for_timeout(200)
    check(page.evaluate("db.pautas.find(p => p.exerciseId === 'e3').hasta") is None, '«Continua» quita la fecha de fin')

    print('\n[5b] Fecha de inicio de una pauta')
    editar('Core básico'); page.fill('#epIni', '2026-02-01')
    page.locator('#modal').get_by_role('button', name='Guardar', exact=True).click(); page.wait_for_timeout(200)
    check(page.evaluate("db.pautas.filter(p => p.bloqueId === 'b1').every(p => p.desde === '2026-02-01')"), 'cambia el inicio de todos los ejercicios del bloque')
    dialogs = []; page.on('dialog', lambda d: dialogs.append(d.message))
    editar('Core básico'); page.fill('#epIni', '2026-04-01'); page.select_option('#epTipo', 'fecha'); page.fill('#epFin', '2026-03-01')
    page.locator('#modal').get_by_role('button', name='Guardar', exact=True).click(); page.wait_for_timeout(200)
    check(any('posterior' in d for d in dialogs) and page.evaluate("db.pautas.find(p => p.bloqueId === 'b1').desde") == '2026-02-01', 'un fin anterior al inicio se rechaza y el modal sigue abierto')
    check(page.locator('#epIni').count() == 1, 'el modal sigue abierto para corregir')
    page.fill('#epIni', '2026-02-01'); page.select_option('#epTipo', 'continua')
    page.locator('#modal').get_by_role('button', name='Guardar', exact=True).click(); page.wait_for_timeout(200)
    check(page.evaluate("db.pautas.filter(p => p.bloqueId === 'b1').every(p => !p.hasta)"), 'vuelve a quedar continua')

    print('\n[5c] Gráfica de puntos del informe')
    page.evaluate("db.puntuaciones[scoreKey('p1', todayIso(), 'e1', 1)] = 3; db.puntuaciones[scoreKey('p1', todayIso(), 'e2', 1)] = 1; idxPunt = null; render()")
    page.get_by_role('tab', name='Calendario').click(); page.locator('#subCal').get_by_role('button', name='Resumen').click(); page.wait_for_timeout(100)
    page.get_by_role('button', name='Semana', exact=True).last.click(); page.get_by_role('button', name='Puntos', exact=True).click(); page.wait_for_timeout(150)
    svg = page.locator('#sec-resumen svg')
    textos = [(t or '').strip() for t in svg.locator('text').evaluate_all('els => els.map(e => e.textContent)')]
    check(any('Core básico' in t for t in textos) and any('sueltos' in t for t in textos), f'filas agrupadas por bloque: {[t for t in textos if len(t) > 3][:4]}')
    check(any(t.startswith('Plancha lateral') for t in textos) and not any('…' in t for t in textos), 'nombres completos, sin recortar')
    check({'3', '1'} <= set(textos), 'los puntos muestran su valor numérico')
    check(svg.locator('circle').first.get_attribute('r') == '12', 'puntos más grandes')
    page.get_by_role('tab', name='Calendario').click(); page.locator('#subCal').get_by_role('button', name='Calendario').click(); page.wait_for_timeout(100)
    check(page.locator('.sticky-head').get_by_role('button', name='Generar informe de pautas…').count() == 0, 'el botón de informe no está en la cabecera')

    print('\n[6] Formulario de hitos')
    page.get_by_role('tab', name='Progreso').click(); page.get_by_role('menuitem', name='Hitos').click(); page.wait_for_timeout(100)
    if page.locator('#hNota').is_hidden(): page.get_by_role('button', name='Nuevo hito…').click(); page.wait_for_timeout(100)
    cajas = {k: page.locator(sel).bounding_box() for k, sel in [('f', '#hFecha'), ('n', '#hNota'), ('b', '#sec-hitos .hito-form button.btn')]}
    check(abs(cajas['f']['y'] + cajas['f']['height'] - (cajas['n']['y'] + cajas['n']['height'])) < 3 or abs(cajas['f']['y'] - cajas['n']['y']) < 3, 'fecha y notas alineadas')
    check(cajas['b']['y'] >= cajas['n']['y'] + cajas['n']['height'] and abs(cajas['b']['x'] + cajas['b']['width'] - (cajas['n']['x'] + cajas['n']['width'])) < 3, 'el botón queda bajo el formulario, alineado a la derecha')
    check(cajas['n']['width'] > cajas['f']['width'] * 2, 'el campo de notas ocupa el espacio sobrante')
    page.screenshot(path='/tmp/hitos_form.png', clip={'x': 0, 'y': page.locator('#sec-hitos').bounding_box()['y'] - 10, 'width': 1300, 'height': 260})
    print('\n[7] Puntuar no devuelve al principio de la ventana')
    page.set_viewport_size({'width': 1300, 'height': 400})
    page.get_by_role('tab', name='Calendario').click(); page.locator('#subCal').get_by_role('button', name='Calendario').click(); page.wait_for_timeout(100)
    page.evaluate("openDay(todayIso())"); page.wait_for_selector('#modal .grp-dia')
    sc = lambda: page.evaluate("document.querySelector('#modal .mwrap > .card').scrollTop")
    boton = page.locator('#modal .ej-dia').nth(1).locator('.scores button').nth(2)
    boton.scroll_into_view_if_needed(); page.wait_for_timeout(100)
    antes = sc()
    boton.click(); page.wait_for_timeout(250)
    check(antes > 0 and abs(sc() - antes) <= 2, f'la posición se mantiene al puntuar ({antes} → {sc()})')
    rep = page.locator('#modal .ej-dia').nth(1).get_by_role('button', name='Añadir repetición')
    rep.scroll_into_view_if_needed(); page.wait_for_timeout(100)
    antes = sc(); rep.click(); page.wait_for_timeout(250)
    check(abs(sc() - antes) <= 2, f'y al añadir una repetición ({antes} → {sc()})')
    page.set_viewport_size({'width': 1300, 'height': 900})

    print('\n[8] Asignar ejercicios a un día con el mismo formulario que en Pautas')
    page.evaluate("db.bloques.push({id:'b2', nombre:'Respiración guiada', nivel:'B', ejercicios:['e4']}); render()")
    mañana = page.evaluate("addDays(todayIso(), 1)")
    page.evaluate(f"openDay('{mañana}', 'anadir')"); page.wait_for_selector('#secAdd .lista-sel')
    check(page.locator('#secAdd .lista-sel.vertical').count() == 1 and page.locator('#secAdd input[type=search]').count() == 1 and page.locator('#secAdd #aNivel').count() == 1, 'mismo selector: buscador, filtro y lista vertical')
    check(page.locator('#secAdd .exItem').count() == 1 and page.locator('#secAdd .bItem').count() == 1, 'solo se ofrece lo que aún no está en ese día')
    check('nivel b' in page.locator('#secAdd .gTitulo').first.inner_text().lower(), 'bloques agrupados por nivel')
    page.locator('#secAdd .bItem input').check()
    page.get_by_role('button', name='Añadir al día').click(); page.wait_for_timeout(250)
    nuevas = page.evaluate(f"db.pautas.filter(p => p.exerciseId === 'e4')")
    check(len(nuevas) == 1 and nuevas[0]['desde'] == nuevas[0]['hasta'] == mañana and nuevas[0]['bloqueId'] == 'b2', 'el bloque se añade solo a ese día, conservando su bloque')
    check('Respiración guiada' in page.locator('#modal .grp-titulo').all_inner_texts()[-1] , 'en la puntuación aparece bajo el nombre del bloque')
    page.keyboard.press('Escape')

    check(not errors, 'sin errores de consola: ' + '; '.join(errors[:3]))
    br.close()
print('\nRESULTADO:', 'TODO OK' if ok else 'HAY FALLOS'); sys.exit(0 if ok else 1)
