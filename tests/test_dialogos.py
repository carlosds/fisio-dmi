# Ventanas propias (avisos, confirmaciones, texto y «escribe BORRAR»), «Deshacer» y botón Atrás del navegador.
# Uso: MOCK_DIALOGOS=propios python3 mock_server.py PUERTO seed_nuevo.json & ; python3 test_dialogos.py PUERTO
import json, sys, urllib.request
from playwright.sync_api import sync_playwright
PORT = sys.argv[1]; BASE = f'http://127.0.0.1:{PORT}'
fails = []
def check(c, m):
    print(('  ok  ' if c else '  FALLA ') + m)
    if not c: fails.append(m)
st = lambda: json.loads(urllib.request.urlopen(BASE + '/__state').read())

with sync_playwright() as pw:
    b = pw.chromium.launch(); page = b.new_page(viewport={'width': 1300, 'height': 900})
    errs = []; page.on('pageerror', lambda e: errs.append(str(e)))
    nativos = []; page.on('dialog', lambda d: (nativos.append(d.message), d.dismiss()))
    page.goto(BASE + '/'); page.wait_for_selector('#listaPacientes .fila-pac'); page.evaluate('descartarNovedades()')
    dlg = page.locator('#dialogo .dlg')
    hoy = page.evaluate('todayIso()')

    print('\n[1] Confirmación propia al eliminar, y Deshacer')
    page.evaluate("db.patients.push({ id: 'p2', nombre: 'Luis', apellidos: 'Otro', telefono: '', email: '', fechaAlta: '2026-01-01', foto: '' }); db.hitos.push({ id: 'h9', patientId: 'p2', fecha: '2026-02-01', nota: 'x', fotos: [] }); render()")
    page.wait_for_timeout(300)
    page.locator('#listaPacientes .fila-pac', has_text='Otro').locator('input[type=checkbox]').check()
    page.get_by_role('button', name='Eliminar (1)').click(); dlg.wait_for(); page.wait_for_timeout(100)
    check('Luis Otro' in dlg.inner_text() and dlg.get_by_role('button', name='Eliminar paciente').count() == 1, 'ventana propia con el nombre y botón «Eliminar paciente»')
    check('rojo' in dlg.get_by_role('button', name='Eliminar paciente').get_attribute('class'), 'el botón de borrar va en rojo')
    check(page.evaluate("document.activeElement.id") == 'dlgNo', 'el foco empieza en «Cancelar» (lo seguro)')
    check(page.evaluate("document.querySelector('#main').inert") is True, 'lo de detrás queda bloqueado')
    page.keyboard.press('Escape'); page.wait_for_timeout(150)
    check(dlg.count() == 0 and page.evaluate("db.patients.some(p => p.id === 'p2')"), 'Esc cancela y no borra nada')
    check(page.evaluate("document.querySelector('#main').inert") is False, 'y desbloquea la pantalla')
    page.get_by_role('button', name='Eliminar (1)').click(); dlg.wait_for()
    dlg.get_by_role('button', name='Eliminar paciente').click(); page.wait_for_timeout(500)
    check(not any(p['id'] == 'p2' for p in st()['patients']) and not st()['hitos'], 'al confirmar se borra (también en el servidor)')
    bar = page.locator('#deshacer.visible')
    check(bar.count() == 1 and 'Luis Otro eliminado' in bar.inner_text(), 'aparece «Deshacer» con lo que se ha borrado')
    bar.get_by_role('button', name='Deshacer').click(); page.wait_for_timeout(500)
    check(any(p['id'] == 'p2' for p in st()['patients']) and len(st()['hitos']) == 1, 'Deshacer recupera al paciente y sus hitos (también en el servidor)')
    check(page.locator('#deshacer.visible').count() == 0 and 'Otro, Luis' in page.locator('#listaPacientes').inner_text(), 'el aviso se va y vuelve a estar en la lista')

    print('\n[2] Cmd/Ctrl+Z y aviso propio')
    page.evaluate("go('ejercicios')"); page.wait_for_timeout(150)
    item = page.locator('#listaEjercicios .item', has_text='Respiración diafragmática')
    item.get_by_role('button', name='Acciones de Respiración diafragmática').click(); item.get_by_role('button', name='Eliminar…').click(); dlg.wait_for()
    dlg.get_by_role('button', name='Eliminar').click(); page.wait_for_timeout(300)
    check(not page.evaluate("db.exercises.some(e => e.id === 'e4')"), 'ejercicio eliminado')
    page.keyboard.press('Control+z'); page.wait_for_timeout(300)
    check(page.evaluate("db.exercises.some(e => e.id === 'e4')"), 'Ctrl+Z lo recupera')
    page.get_by_role('button', name='Nuevo ejercicio…').click(); page.fill('#nuevoEj', 'puente GLÚTEO'); page.keyboard.press('Enter'); dlg.wait_for()
    check('Ya existe un ejercicio con ese nombre' in dlg.inner_text() and dlg.get_by_role('button', name='Cancelar').count() == 0, 'los avisos salen en ventana propia, con un solo botón')
    page.keyboard.press('Escape'); page.wait_for_timeout(150)
    check(dlg.count() == 0 and page.locator('#nuevoEj').count() == 1, 'Esc cierra solo el aviso; la ventana de debajo sigue abierta')
    page.evaluate('closeModal()')

    print('\n[3] Pedir texto (renombrar)')
    item = page.locator('#listaEjercicios .item', has_text='Plancha lateral')
    item.get_by_role('button', name='Acciones de Plancha lateral').click(); item.get_by_role('button', name='Renombrar…').click(); dlg.wait_for()
    check('Core básico' in dlg.inner_text() and page.locator('#dlgCampo').count() == 0, 'primero avisa de los bloques que lo usan')
    dlg.get_by_role('button', name='Aceptar').click(); page.wait_for_selector('#dlgCampo'); page.wait_for_timeout(100)
    check(page.locator('#dlgCampo').input_value() == 'Plancha lateral' and page.evaluate("document.activeElement.id") == 'dlgCampo', 'el campo trae el nombre actual y tiene el foco')
    page.fill('#dlgCampo', 'Plancha lateral corta'); page.keyboard.press('Enter'); page.wait_for_timeout(300)
    check(page.evaluate("getE('e2').nombre") == 'Plancha lateral corta', 'Intro acepta el nuevo nombre')

    print('\n[4] Borrar todo: hay que escribir BORRAR')
    page.evaluate("ui.ajTab = 'datos'; go('ajustes')"); page.wait_for_timeout(200)
    page.get_by_role('button', name='Borrar todo').click(); dlg.wait_for()
    si = dlg.get_by_role('button', name='Borrar todo')
    check(si.is_disabled() and 'BORRAR' in dlg.inner_text(), 'el botón está desactivado hasta escribir la palabra')
    page.fill('#dlgCampo', 'borra'); check(si.is_disabled(), 'una palabra incompleta no vale')
    page.keyboard.press('Enter'); page.wait_for_timeout(100)
    check(dlg.count() == 1 and page.evaluate('db.patients.length') == 2, 'Intro tampoco borra sin la palabra')
    page.fill('#dlgCampo', 'borrar'); check(si.is_enabled(), 'con «borrar» (sin importar mayúsculas) se activa')
    si.click(); page.wait_for_timeout(400)
    check(page.evaluate('db.patients.length') == 0 and st()['patients'] == [], 'se borra todo')
    page.locator('#deshacer').get_by_role('button', name='Deshacer').click(); page.wait_for_timeout(400)
    check(len(st()['patients']) == 2, 'y también se puede deshacer')

    print('\n[5] Atrás y Adelante del navegador')
    page.evaluate("go('pacientes')"); page.wait_for_timeout(100)
    page.locator('#listaPacientes a', has_text='López Pérez').click(); page.wait_for_timeout(150)
    page.get_by_role('tab', name='Calendario').click(); page.wait_for_timeout(150)
    check(page.evaluate('location.hash') == '#/paciente/p1/calendario', f'cada pantalla tiene su dirección ({page.evaluate("location.hash")})')
    page.locator('#subCal').get_by_role('button', name='Resumen').click(); page.wait_for_timeout(150)
    page.go_back(); page.wait_for_timeout(250)
    check(page.evaluate("ui.view + ui.tabP + ui.calVista") == 'pacientecalendariocalendario', 'Atrás: del Resumen al Calendario')
    page.go_back(); page.wait_for_timeout(250)
    check(page.evaluate("ui.tabP") == 'pautas', 'Atrás: a la pestaña Pautas')
    page.go_back(); page.wait_for_timeout(250)
    check(page.evaluate("ui.view") == 'pacientes' and page.locator('#listaPacientes').count() == 1, 'Atrás: a la lista de pacientes')
    page.go_forward(); page.wait_for_timeout(250)
    check(page.evaluate("ui.view + ui.patientId") == 'pacientep1', 'Adelante: vuelve a la ficha')
    page.get_by_role('tab', name='Calendario').click(); page.wait_for_timeout(150)
    page.evaluate(f"openDay('{hoy}')"); page.wait_for_selector('#modal .ej-dia')
    page.go_back(); page.wait_for_timeout(250)
    check(page.locator('#modal').inner_html() == '' and page.evaluate("ui.view + ui.tabP") == 'pacientecalendario', 'con una ventana abierta, Atrás solo la cierra')
    page.evaluate(f"openDay('{hoy}')"); page.wait_for_selector('#modal .ej-dia')
    page.locator('#modal .modalx').click(); page.wait_for_timeout(250)
    page.go_back(); page.wait_for_timeout(250)
    check(page.evaluate("ui.tabP") == 'pautas', 'cerrar la ventana con × no deja un paso de más en el historial')
    page.evaluate("irTab('calendario')"); page.wait_for_timeout(100)
    page.reload(); page.wait_for_selector('#main .ptabs'); page.wait_for_timeout(300)
    check(page.evaluate("ui.view + ui.patientId + ui.tabP") == 'pacientep1calendario', 'al recargar, sigue en la misma pantalla')

    print('\n[6] Quitar un ejercicio de un día: ventana propia encima de la del día, teclado bloqueado y Deshacer')
    page.evaluate(f"openDay('{hoy}')"); page.wait_for_selector('#modal .ej-dia')
    n0 = page.locator('#modal .ej-dia').count()
    page.locator('#modal').get_by_role('button', name='Quitar todos los ejercicios').click(); dlg.wait_for()
    page.keyboard.press('2'); page.wait_for_timeout(150)
    check(page.evaluate(f"Object.keys(db.puntuaciones).filter(k => k.includes('{hoy}')).length") == 0, 'con la ventana abierta, las teclas no puntúan')
    dlg.get_by_role('button', name='Aceptar').click(); page.wait_for_timeout(300)
    check('No hay ejercicios asignados' in page.locator('#modal').inner_text(), 'el día queda vacío')
    page.locator('#deshacer').get_by_role('button', name='Deshacer').click(); page.wait_for_timeout(300)
    check(page.locator('#modal .ej-dia').count() == n0, f'Deshacer vuelve a poner los {n0} ejercicios y la ventana del día se actualiza')

    print('\n[7] Elegir entre varias respuestas (cita que se repite)')
    page.evaluate("closeModal(); go('agenda')"); page.wait_for_timeout(150)
    page.evaluate("const s = { id: 's1', patientId: 'p1', dias: '24', hora: '17:00', duracion: 45, desde: addDays(todayIso(), 1), hasta: addDays(todayIso(), 20), nota: '', excluidas: [] }; db.seriesCitas.push(s); generarSerie(db, s); render()")
    primera = page.evaluate("db.citas.filter(c => c.serieId).sort((a, b) => a.fecha.localeCompare(b.fecha))[0].id")
    page.evaluate(f"openCita('{primera}')"); page.wait_for_selector('#ctHora')
    page.fill('#ctHora', '18:00'); page.locator('#modal').get_by_role('button', name='Guardar').click(); dlg.wait_for(); page.wait_for_timeout(100)
    check(dlg.locator('button').all_inner_texts() == ['Cancelar', 'Solo esta sesión', 'Esta y las siguientes'], f'tres botones: Cancelar, Solo esta sesión y Esta y las siguientes ({dlg.locator("button").all_inner_texts()})')
    check(page.evaluate("document.activeElement.textContent") == 'Solo esta sesión', 'el foco empieza en la primera opción')
    page.keyboard.press('Escape'); page.wait_for_timeout(150)
    check(dlg.count() == 0 and page.evaluate(f"getCita('{primera}').hora") == '17:00' and page.locator('#ctHora').count() == 1, 'Esc cancela sin cambiar nada (la ventana de la cita sigue abierta)')
    page.locator('#modal').get_by_role('button', name='Guardar').click(); dlg.wait_for()
    dlg.get_by_role('button', name='Esta y las siguientes').click(); page.wait_for_timeout(300)
    check(page.evaluate("db.citas.filter(c => c.serieId).every(c => c.hora === '18:00')"), 'elegir «Esta y las siguientes» cambia toda la serie desde esa cita')

    print('\n[8] Sin ventanas del navegador')
    check(not nativos, f'no ha salido ninguna ventana nativa del navegador ({nativos[:2]})')
    check(not errs, f'sin errores JS {errs}')
    b.close()
print('\nRESULTADO:', 'TODO OK' if not fails else f'{len(fails)} FALLOS')
sys.exit(1 if fails else 0)
